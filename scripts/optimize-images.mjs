// Generates resized WebP variants of every image in images-src/ into public/img/,
// plus src/imageManifest.ts describing them. Run after adding or changing photos:
//   npm run images
import { mkdir, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const ROOT = path.resolve(import.meta.dirname, "..");
const SRC_DIR = path.join(ROOT, "images-src");
const OUT_DIR = path.join(ROOT, "public", "img");
const MANIFEST = path.join(ROOT, "src", "imageManifest.ts");

const WIDTHS = [640, 1280, 1920];
const QUALITY = 72;
// The hero sits under a dark gradient overlay, so it hides heavier compression
const QUALITY_OVERRIDES = { "outback-hero-aerial-dark-2": 55 };

const files = (await readdir(SRC_DIR)).filter((f) => /\.(jpe?g|png)$/i.test(f)).sort();

await rm(OUT_DIR, { recursive: true, force: true });
await mkdir(OUT_DIR, { recursive: true });

const manifest = {};
let totalOut = 0;

for (const file of files) {
    const name = path.parse(file).name;
    const input = path.join(SRC_DIR, file);
    const meta = await sharp(input).metadata();
    // EXIF orientations 5-8 are rotated 90°, so width and height swap once applied
    const rotated = (meta.orientation ?? 1) >= 5;
    const srcWidth = rotated ? meta.height : meta.width;
    const srcHeight = rotated ? meta.width : meta.height;

    // Cap the longest edge, so portrait photos aren't 1920 wide and ~2900 tall
    const longEdge = WIDTHS.at(-1);
    const maxWidth = Math.min(srcWidth, longEdge, Math.round((longEdge * srcWidth) / srcHeight));
    const widths = [...new Set([...WIDTHS.filter((w) => w < maxWidth), maxWidth])];

    for (const width of widths) {
        const info = await sharp(input)
            .rotate()
            .resize({ width, withoutEnlargement: true })
            .webp({ quality: QUALITY_OVERRIDES[name] ?? QUALITY, effort: 5 })
            .toFile(path.join(OUT_DIR, `${name}-${width}.webp`));
        totalOut += info.size;
    }

    manifest[name] = {
        width: maxWidth,
        height: Math.round((srcHeight * maxWidth) / srcWidth),
        widths,
    };
    console.log(`${name}: ${srcWidth}x${srcHeight} -> ${widths.join("/")}w`);
}

await writeFile(
    MANIFEST,
    "// Generated by scripts/optimize-images.mjs — do not edit by hand.\n" +
        `export const imageManifest = ${JSON.stringify(manifest, null, 4)} as const;\n`,
);

console.log(`\n${files.length} images, ${Object.values(manifest).reduce((n, m) => n + m.widths.length, 0)} variants written to public/img/`);
console.log(`total variant size: ${(totalOut / 1024 / 1024).toFixed(1)} MB`);
